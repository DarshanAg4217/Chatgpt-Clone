const mongoose = require('mongoose');
const { Schema } = mongoose;


const userSchema = new Schema({
    fullname: {
        firstname: {
            type: String,
            required: true
        },
        lastname: {
            type: String,
            required: true
        }
    },
    email: {
        type: String,
        required: true,
        unique: true
    },
    password: {
        type: String,
        required: true
    }
}, { timestamps: true });


const userModel = mongoose.model('user', userSchema);


module.exports = userModel;